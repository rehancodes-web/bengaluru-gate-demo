// Builds real-rain.js from NASA POWER data (Track A: real satellite-derived data).
// Inputs (downloaded with curl, no account needed):
//   tools/nasa-power-hourly-2022.json  hourly PRECTOTCORR, 26 Aug – 8 Sep 2022, lat 12.95 lon 77.62 (east Bengaluru), local time
//   tools/nasa-power-daily-2022.json   daily PRECTOTCORR, 1 Jun – 30 Sep 2022, same point
// Then replays the hourly rain through the lake-outlet gate model three ways and records the result:
//   no gate (outlet stays shut, water leaves only over the bank), gate on automatic, automatic + pre-release
//   before the forecast storm. Run: node tools/build-real-rain.cjs
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname);
const H = JSON.parse(fs.readFileSync(path.join(dir, 'nasa-power-hourly-2022.json'), 'utf8'));
const Dd = JSON.parse(fs.readFileSync(path.join(dir, 'nasa-power-daily-2022.json'), 'utf8'));
const hourlyObj = H.properties.parameter.PRECTOTCORR, dailyObj = Dd.properties.parameter.PRECTOTCORR;
const keys = Object.keys(hourlyObj).sort(), hourly = keys.map(k => Math.max(0, hourlyObj[k]));
const monthly = {}; for (const [k, v] of Object.entries(dailyObj)) { const m = k.slice(0, 6); monthly[m] = (monthly[m] || 0) + Math.max(0, v); }
const RAIN = {
  source: 'NASA POWER hourly API v2.10, parameter PRECTOTCORR (MERRA-2 reanalysis with satellite data assimilation), retrieved ' + new Date().toISOString().slice(0, 10),
  point: { lat: 12.95, lon: 77.62, note: 'East Bengaluru (Bellandur / Outer Ring Road area). Grid cell about 50 km, so local cloudburst peaks are smoothed.' },
  start: keys[0], timeStandard: 'Local solar time', hourly, monthlyTotals: Object.fromEntries(Object.entries(monthly).map(([k, v]) => [k, +v.toFixed(1)])),
  catchment: { km2: 3, runoff: 0.75, note: 'Illustrative urban catchment draining to one 6 ha lake; 1 mm/h of rain gives 0.625 m³/s of inflow.' }
};

// ---- replay through the gate model ----
const GT = require(path.join(dir, '..', 'gate-types.js'));
require(path.join(dir, '..', 'real-rain-scenario.js'))(GT, RAIN);
const NAME = GT.REAL_SCENARIO, dur = hourly.length * 3600;
function run(mode) {
  const m = GT.create('vertical', NAME, 'Healthy'); let peak = 0, preDone = false, stormPeak = 0; const s0 = keys.indexOf('2022090400') * 3600, s1 = keys.indexOf('2022090700') * 3600;
  if (mode === 'none') GT.command(m, 0);                          // a lake with no operable gate
  const forecastAt = (RAIN.preReleaseHour || 0) * 3600;
  for (let t = 0; t < dur; t++) {
    if (mode === 'pre' && !preDone && t >= forecastAt) { GT.command(m, 100, { override: false }); preDone = 'running'; }
    if (mode === 'pre' && preDone === 'running' && t >= s1) { GT.setMode(m, 'auto'); preDone = true; } // forecast mode: stay open through the forecast storm window, interlocks still active
    GT.step(m); peak = Math.max(peak, m.last.h1); if (t >= s0 && t < s1) stormPeak = Math.max(stormPeak, m.last.h1);
  }
  return { peakLake: +peak.toFixed(2), stormPeak4to6Sep: +stormPeak.toFixed(2), lakeSpill: Math.round(m.tot.spill1), drainSpill: Math.round(m.tot.spill2), released: Math.round(m.tot.out), balance: GT.balanceError(m) };
}
// forecast mode: open fully 24 h before the 4 Sep storm and keep releasing until 7 Sep 00:00, then back to automatic
RAIN.preReleaseHour = keys.indexOf('2022090400') - 24;
RAIN.replay = { model: 'Vertical lift gate on a 6 ha lake (illustrative), real hourly rain 26 Aug – 8 Sep 2022', noGate: run('none'), auto: run('auto'), preRelease: run('pre'), preReleaseAt: keys[RAIN.preReleaseHour] };
fs.writeFileSync(path.join(dir, '..', 'real-rain.js'), '// Generated by tools/build-real-rain.cjs from NASA POWER data. Do not edit by hand.\n(function(r){const RAIN=' + JSON.stringify(RAIN) + ';if(typeof module!=="undefined"&&module.exports)module.exports=RAIN;else{r.REAL_RAIN=RAIN;if(r.GateTypes&&r.RealRainScenario)r.RealRainScenario(r.GateTypes,RAIN);}})(typeof globalThis!=="undefined"?globalThis:this);\n');
console.log(JSON.stringify(RAIN.replay, null, 1));
